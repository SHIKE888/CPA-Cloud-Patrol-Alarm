#!/bin/sh
#=============================================================================
# board_src_toggle.sh —— 反复切源压力测试
#
#   目的: 验证运行中反复写 0xDB 来回切，目标那一路每次都能重新对齐，
#         不会卡死、不需要重启。
#
#   用法: sh board_src_toggle.sh [轮数] [每轮等待秒]
#         默认 4 轮 x 3s
#
#   每轮: 写 0xDB -> 等 -> 读 0xD6/0xD7/0xD8/0xD4/D5
#         期望(有模组的那一路): manual=1, autodone=1, in_frame=1
#         期望(空的那一路):     全 0 / manual=0
#=============================================================================
DEV=${DEV:-9}
ADDR=${ADDR:-0x40}
N=${1:-4}
W=${2:-3}

g() { printf '%s' "$(i2cget -y $DEV $ADDR $1 2>/dev/null)"; }

echo "=============================================================="
echo " 反复切源 $N 轮, 每轮等 ${W}s"
echo "=============================================================="
fails=0
i=0
while [ $i -lt $N ]; do
    for src in 1 0 1; do
        i2cset -y $DEV $ADDR 0xdb $src >/dev/null 2>&1
        rb=$(g 0xdb)
        sleep $W
        d6=$(g 0xd6); d7=$(g 0xd7); d8=$(g 0xd8)
        printf '  round %d  cam%d (0xDB=%s)  D6=%s D7=%s D8=%s\n' \
               "$i" "$src" "$rb" "$d6" "$d7" "$d8"
        # 源是 1 时必须有数据；此时 in_frame(bit5) 应为 1
        if [ "$src" = "1" ]; then
            case "$d6" in
                0x2?|0x3?|0x6?|0x7?|0xa?|0xb?|0xe?|0xf?) : ;;
                *) echo "     !! cam1 这一轮没在传输 (D6=$d6)"; fails=$((fails+1)) ;;
            esac
        fi
    done
    i=$((i+1))
done

echo "=============================================================="
if [ $fails -eq 0 ]; then
    echo " 结论: 反复切源全部正常, cam1 每次都能重新对齐"
else
    echo " 结论: 有 $fails 次 cam1 没起来 —— 切源后重对齐有问题"
fi
echo "=============================================================="
