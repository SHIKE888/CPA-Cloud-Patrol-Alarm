#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""gen_jpeg_ll_e2e.py —— 无损模式端到端仿真的输入 / 参考输出

生成:
    fpga/sim/jpeg_in.hex      YUV422 word (与有损仿真相同格式)
    fpga/sim/ref.jpg          无损 JPEG 参考 (SOF3)
    fpga/sim/jpeg_sim_cfg.vh  尺寸宏

用法: python tools/gen_jpeg_ll_e2e.py [W] [H]
"""
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
if HERE not in sys.path:
    sys.path.insert(0, HERE)

from jpeg_ref import encode_lossless       # noqa: E402
from gen_jpeg_e2e import make_yuv          # noqa: E402

SIM = os.path.normpath(os.path.join(HERE, "..", "fpga", "sim"))


def main():
    w = int(sys.argv[1]) if len(sys.argv) > 1 else 64
    h = int(sys.argv[2]) if len(sys.argv) > 2 else 16
    assert w % 16 == 0 and h % 8 == 0, "W 必须是 16 的倍数, H 必须是 8 的倍数"

    Y, Cb, Cr = make_yuv(w, h)

    lines = []
    for r in range(h):
        for c in range(w // 2):
            v = ((int(Cr[r, c]) << 24) | (int(Y[r, 2 * c + 1]) << 16)
                 | (int(Cb[r, c]) << 8) | int(Y[r, 2 * c]))
            lines.append("%08x" % v)

    with open(os.path.join(SIM, "jpeg_in.hex"), "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(lines) + "\n")

    with open(os.path.join(SIM, "jpeg_sim_cfg.vh"), "w", encoding="ascii", newline="\n") as f:
        f.write("// generated by tools/gen_jpeg_ll_e2e.py -- do not edit\n")
        f.write("`define SIM_W %d\n" % w)
        f.write("`define SIM_H %d\n" % h)
        f.write("`define SIM_LL 1'b1\n")

    data, st = encode_lossless((Y, Cb, Cr), verbose=False)
    with open(os.path.join(SIM, "ref.jpg"), "wb") as f:
        f.write(data)

    import hashlib
    print("W=%d H=%d  words=%d" % (w, h, len(lines)))
    print("ref_ll.jpg = %d bytes  md5=%s  symbols=%d stuff=%d"
          % (len(data), hashlib.md5(data).hexdigest(), st['symbols'], st['stuff']))


if __name__ == "__main__":
    main()
